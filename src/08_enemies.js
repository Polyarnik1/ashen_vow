// Финальный выбор Короля в прохождении без убийств: он сам просит о смерти (как Азгор), но решает игрок
async function kingResolve(e) {
  e.finaleDone = true; e.finalStrike = false;
  B.bubbles = []; B.heroPose = 'idle';
  sfx('chime', { vol: 0.5, rate: 0.7 });
  await btext('Король опускает скипетр. Печать замирает. В зале становится тихо-тихо.');
  const voices = e.mercy >= 100;
  await btext(voices ? '[y]Король:[/] «Они говорят со мной... Я слышу каждого. И всё равно — прошу, закончи».' : '[y]Король:[/] «Ты не поднял меча на живое. Только твой удар может разорвать печать. Прошу, рыцарь».');
  const c = await choose(['Ударить', 'Пощадить'], { title: 'Король ждёт. Руки опущены.' });
  if (c === 0) {
    setF('king_mercy_strike'); e.finalStrike = true;
    await btext('Ты поднимаешь меч. Король закрывает глаза и улыбается — впервые за сто лет.');
    await heroStrike(e, e.hp + 5, true, true);
    return;
  }
  if (!voices) {
    sfx('deny');
    await btext('[y]Король:[/] «Милосердный... Но пока я жив, они спят. Твоя пощада их не разбудит».');
    await btext('[y]Король:[/] «Если не можешь ударить — найди их голоса. И тогда решай».');
    e.finaleDone = false; e.hp = Math.max(e.hp, Math.ceil(e.maxhp * 0.3)); e.pacRefused = true;
    return;
  }
  await spareEnemy(e);
}
